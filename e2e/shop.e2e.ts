import { test, expect } from "@playwright/test";
test("shop flow", async ({ browser }) => {
  const B = "http://localhost:3000";
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const shop = await ctx.newPage();
  await ctx.request.post(B + "/api/session", { data: { role: "operator", key: "demo-operator" } });
  await ctx.request.post(B + "/api/lab/reset");
  await shop.goto(B + "/shop");
  await shop.screenshot({ path: "docs-verify/screenshots/shop-1-start.png" });
  await shop.getByRole("button", { name: "Pay with CounterSign" }).click();
  await expect(shop.getByText("Waiting for the customer")).toBeVisible();
  const id = (await shop.locator("p.ident").last().textContent())!.trim();
  await ctx.request.post(B + "/api/session", { data: { role: "customer", key: "demo-customer" } });
  const pr = await (await ctx.request.post(`${B}/api/agreements/${id}/pairing`)).json();
  const ph = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
  const phone = await ph.newPage();
  await phone.goto(B + pr.approvePath);
  await phone.getByTestId("approve").click({ delay: 1100 });
  await expect(shop.getByText("Order confirmed")).toBeVisible({ timeout: 15000 });
  await shop.screenshot({ path: "docs-verify/screenshots/shop-2-paid.png" });
  const desk = await ctx.newPage();
  await desk.goto(B + "/command");
  await expect(desk.locator('[data-value="90000"]').first()).toBeVisible();
  await desk.waitForTimeout(1200);
  await desk.screenshot({ path: "docs-verify/screenshots/command-okx.png" });
  await phone.screenshot({ path: "docs-verify/screenshots/phone-okx-settled.png" });
  const s = await (await ctx.request.get(B + "/api/state")).json();
  expect(s.agreements[0].executionCount).toBe(1);
});
